using System.Security.Cryptography;
using Npgsql;

namespace ResourceHub.Tests.Infrastructure;

/// <summary>Reads the test database connection string from RESOURCEHUB_TEST_DB.</summary>
public static class TestDb
{
    public const string EnvironmentVariable = "RESOURCEHUB_TEST_DB";

    public static string? BaseConnectionString =>
        Environment.GetEnvironmentVariable(EnvironmentVariable) is { Length: > 0 } value ? value : null;

    /// <summary>Same server and credentials, different database name.</summary>
    public static string ForDatabase(string databaseName)
    {
        var builder = new NpgsqlConnectionStringBuilder(BaseConnectionString) { Database = databaseName };
        return builder.ConnectionString;
    }

    /// <summary>Same server and database, logging in as another role.</summary>
    public static string ForRole(string databaseName, string role, string password)
    {
        var builder = new NpgsqlConnectionStringBuilder(BaseConnectionString)
        {
            Database = databaseName,
            Username = role,
            Password = password,
        };
        return builder.ConnectionString;
    }

    public static string NewPassword() => Convert.ToHexString(RandomNumberGenerator.GetBytes(16));

    /// <summary>
    /// Creates a database owned by <paramref name="owner"/> and a runtime role that may only
    /// connect, the same layout db/init/01-app-role.sh sets up for Compose. Needs a test user that
    /// may create roles and databases. Names and passwords are generated by the tests (GUID and hex
    /// characters), never taken from input.
    /// </summary>
    public static async Task CreateDatabaseWithRolesAsync(string database, DbRole owner, DbRole runtime)
    {
        await using (var server = new NpgsqlConnection(BaseConnectionString))
        {
            await server.OpenAsync();
            await ExecAsync(server, $"""
                CREATE ROLE "{owner.Name}" LOGIN PASSWORD '{owner.Password}'
                    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
                CREATE ROLE "{runtime.Name}" LOGIN PASSWORD '{runtime.Password}'
                    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS NOINHERIT;
                """);
            await ExecAsync(server, $"CREATE DATABASE \"{database}\" OWNER \"{owner.Name}\"");
            await ExecAsync(server, $"""
                REVOKE ALL ON DATABASE "{database}" FROM PUBLIC;
                GRANT CONNECT ON DATABASE "{database}" TO "{runtime.Name}";
                """);
        }

        await using var db = new NpgsqlConnection(ForDatabase(database));
        await db.OpenAsync();
        await ExecAsync(db, $"""
            REVOKE ALL ON SCHEMA public FROM PUBLIC;
            ALTER SCHEMA public OWNER TO "{owner.Name}";
            GRANT USAGE ON SCHEMA public TO "{runtime.Name}";
            """);
    }

    /// <summary>Drops the database, then the roles (they own nothing once it is gone).</summary>
    public static async Task DropDatabaseAndRolesAsync(string database, params string[] roles)
    {
        if (BaseConnectionString is null)
        {
            return;
        }

        NpgsqlConnection.ClearAllPools();
        await using var server = new NpgsqlConnection(BaseConnectionString);
        await server.OpenAsync();
        await ExecAsync(server, $"DROP DATABASE IF EXISTS \"{database}\" WITH (FORCE)");
        foreach (var role in roles)
        {
            await ExecAsync(server, $"DROP ROLE IF EXISTS \"{role}\"");
        }
    }

    private static async Task ExecAsync(NpgsqlConnection connection, string sql)
    {
        await using var command = connection.CreateCommand();
        command.CommandText = sql;
        await command.ExecuteNonQueryAsync();
    }
}

/// <summary>A login role made for one test class.</summary>
public sealed record DbRole(string Name, string Password)
{
    public static DbRole New(string kind) => new($"rh_test_{kind}_{Guid.NewGuid():N}"[..40], TestDb.NewPassword());
}

/// <summary>A fact that needs PostgreSQL; it is skipped when RESOURCEHUB_TEST_DB is not set.</summary>
public sealed class DbFactAttribute : FactAttribute
{
    public DbFactAttribute()
    {
        if (TestDb.BaseConnectionString is null)
        {
            Skip = $"{TestDb.EnvironmentVariable} is not set; this test needs PostgreSQL.";
        }
    }
}

/// <summary>A theory that needs PostgreSQL; it is skipped when RESOURCEHUB_TEST_DB is not set.</summary>
public sealed class DbTheoryAttribute : TheoryAttribute
{
    public DbTheoryAttribute()
    {
        if (TestDb.BaseConnectionString is null)
        {
            Skip = $"{TestDb.EnvironmentVariable} is not set; this test needs PostgreSQL.";
        }
    }
}
